import { chromium } from "playwright";
import assert from "node:assert/strict";
const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL || "msedge",headless:true});
try {
  const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:"reduce"});
  const page=await context.newPage();
  const errors=[]; page.on("pageerror",e=>errors.push(e.message));
  const base=process.env.BASE_URL || "http://127.0.0.1:3000";
  await page.goto(`${base}/chats/room/?id=a2`);
  await page.locator(".chat-agreement-pin button").click();
  const dialog=page.getByRole("dialog",{name:"작업 약속서 작성"});
  await dialog.getByLabel("작업 범위",{exact:true}).fill("메뉴판 1장 디자인");
  await dialog.getByLabel("전달할 결과물").fill("인쇄용 PDF와 원본 파일");
  await dialog.getByLabel("완료 확인 기준").fill("가격 확인 후 파일 수령");
  await dialog.getByRole("button",{name:"다음",exact:true}).click();
  const first=dialog.locator("[data-agreement-day]").nth(5), last=dialog.locator("[data-agreement-day]").nth(10);
  const a=await first.boundingBox(),b=await last.boundingBox();
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2); await page.mouse.down();
  await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:12}); await page.mouse.up();
  assert.equal(await dialog.getByLabel("시작일",{exact:true}).inputValue(),await first.getAttribute("data-agreement-day"));
  assert.equal(await dialog.getByLabel("완료 예정일",{exact:true}).inputValue(),await last.getAttribute("data-agreement-day"));
  await dialog.getByRole("button",{name:"다음",exact:true}).click();
  await dialog.getByLabel("제공할 쿠폰과 지급 시점").fill("완료 후 3일 이내 음료 쿠폰 5장, 3개월 유효");
  await dialog.getByRole("button",{name:"다음",exact:true}).click();
  await dialog.getByRole("button",{name:"저장하고 양쪽 확인받기"}).click();
  await dialog.getByRole("checkbox").check();
  await dialog.getByRole("button",{name:"이 버전 최종 확인"}).click();
  await dialog.getByRole("button",{name:"상대방 확인 대기"}).waitFor();
  const draft=await page.evaluate(()=>JSON.parse(localStorage.getItem("wolgye-mock-v2")).agreements.a2);
  assert(draft.studentConfirmedAt); assert.equal(draft.finalizedAt,null);
  await page.evaluate(()=>localStorage.setItem("wolgye-user","r1"));
  await page.reload(); await page.locator(".chat-agreement-pin button").click();
  await dialog.getByRole("button",{name:"내용 수정"}).click();
  await dialog.getByLabel("작업 범위",{exact:true}).fill("메뉴판 2장 디자인");
  for(let i=0;i<3;i++) await dialog.getByRole("button",{name:"다음",exact:true}).click();
  await dialog.getByRole("button",{name:"저장하고 양쪽 확인받기"}).click();
  await dialog.getByRole("checkbox").waitFor();
  await dialog.getByRole("checkbox").check(); await dialog.getByRole("button",{name:"이 버전 최종 확인"}).click();
  await dialog.getByRole("button",{name:"상대방 확인 대기"}).waitFor();
  const revised=await page.evaluate(()=>JSON.parse(localStorage.getItem("wolgye-mock-v2")).agreements.a2);
  assert.equal(revised.version,2); assert.equal(revised.studentConfirmedAt,null); assert(revised.ownerConfirmedAt); assert.equal(revised.finalizedAt,null);
  await page.evaluate(()=>localStorage.setItem("wolgye-user","s1"));
  await page.reload(); await page.locator(".chat-agreement-pin button").click();
  await dialog.getByRole("checkbox").check(); await dialog.getByRole("button",{name:"이 버전 최종 확인"}).click();
  await dialog.getByRole("heading",{name:"우리의 약속이 확정됐어요"}).waitFor();
  assert.equal(await dialog.getByRole("button",{name:"내용 수정"}).count(),0);
  if(process.env.SHOT_PATH) await page.screenshot({path:process.env.SHOT_PATH});
  assert.deepEqual(errors,[]);
  console.log("PASS: date drag, shared draft, reconfirmation after edits, dual approval, final lock");
} finally { await browser.close(); }
